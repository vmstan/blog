import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import subsetFont from "subset-font";

// Font Awesome ships ~2,000 icons across 86 KB of CSS and 230 KB of webfonts.
// This site uses a few dozen, so we scan the source for the icons actually
// referenced, emit CSS for just those, and subset the fonts to match. Both
// artifacts come out of this one script so the glyphs and the codepoints that
// reference them can never drift apart.

const faRoot = "node_modules/@fortawesome/fontawesome-free";
const scanRoots = ["src/components", "src/data", "src/layouts", "src/pages"];
const cssTarget = "src/styles/icons.css";
const fontDir = "src/styles/fonts";

// Utility classes we support. Anything else found in the source is a hard
// error, so a newly used Font Awesome feature can't silently render as nothing.
const utilities = {
  "fa-rotate-90": ".fa-rotate-90{transform:rotate(90deg)}",
};
const styleClasses = new Set(["fa-solid", "fa-brands"]);

const styles = {
  solid: {
    css: "fontawesome.min.css",
    font: "fa-solid-900.woff2",
    family: "Font Awesome 7 Free",
    weight: 900,
  },
  brands: {
    css: "brands.min.css",
    font: "fa-brands-400.woff2",
    family: "Font Awesome 7 Brands",
    weight: 400,
  },
};

// Font Awesome 7 declares each icon as `.fa-name{--fa:"\f09b"}`.
function codepoints(cssFile) {
  const css = readFileSync(join(faRoot, "css", cssFile), "utf8");
  const map = new Map();
  for (const [, selectors, value] of css.matchAll(
    /([^{}]+)\{--fa:"\\([0-9a-f]+)"\}/g,
  )) {
    for (const selector of selectors.split(",")) {
      const name = selector.trim().replace(/^\./, "");
      if (/^fa-[a-z0-9-]+$/.test(name)) map.set(name, value);
    }
  }
  return map;
}

function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const path = join(dir, entry);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const icons = {
  solid: codepoints(styles.solid.css),
  brands: codepoints(styles.brands.css),
};

const used = new Set();
for (const root of scanRoots) {
  for (const path of walk(root)) {
    const source = readFileSync(path, "utf8");
    for (const [name] of source.matchAll(/\bfa-[a-z][a-z0-9-]*/g)) used.add(name);
  }
}

const chosen = { solid: [], brands: [] };
const unknown = [];
for (const name of [...used].sort()) {
  if (styleClasses.has(name) || utilities[name]) continue;
  // Brands first: a handful of names exist in both faces.
  if (icons.brands.has(name)) chosen.brands.push(name);
  else if (icons.solid.has(name)) chosen.solid.push(name);
  else unknown.push(name);
}

if (unknown.length) {
  console.error(
    `Unknown Font Awesome classes: ${unknown.join(", ")}\n` +
      `Add them to the utilities map in ${import.meta.filename} if they are ` +
      `not icon names.`,
  );
  process.exit(1);
}

mkdirSync(fontDir, { recursive: true });

const faces = [];
const rules = [];
for (const [style, names] of Object.entries(chosen)) {
  const { font, family, weight } = styles[style];
  const map = icons[style];

  const glyphs = names
    .map((name) => String.fromCodePoint(parseInt(map.get(name), 16)))
    .join("");
  const subset = await subsetFont(
    readFileSync(join(faRoot, "webfonts", font)),
    glyphs,
    { targetFormat: "woff2" },
  );
  const subsetName = font.replace(/\.woff2$/, "-subset.woff2");
  writeFileSync(join(fontDir, subsetName), subset);

  faces.push(`@font-face {
  font-family: "${family}";
  font-style: normal;
  font-weight: ${weight};
  font-display: block;
  src: url("./fonts/${subsetName}") format("woff2");
}`);
  rules.push(
    `/* ${style} */\n` +
      names.map((name) => `.${name}{--fa:"\\${map.get(name)}"}`).join("\n"),
  );

  console.log(
    `${style}: ${names.length} icons, ${font} ${readFileSync(join(faRoot, "webfonts", font)).length} -> ${subset.length} bytes`,
  );
}

const version = JSON.parse(
  readFileSync(join(faRoot, "package.json"), "utf8"),
).version;

const css = `/* Generated by scripts/build-icon-css.mjs. Do not edit by hand. */
/* Font Awesome Free ${version} by @fontawesome - https://fontawesome.com
   License - https://fontawesome.com/license/free (Icons: CC BY 4.0, Fonts: SIL OFL 1.1) */

${faces.join("\n\n")}

.fa-solid,
.fa-brands {
  display: var(--fa-display, inline-block);
  width: var(--fa-width, 1.25em);
  font-family: var(--fa-family);
  font-style: normal;
  font-synthesis: none;
  font-variant: normal;
  font-weight: var(--fa-style);
  line-height: 1;
  text-align: center;
  text-rendering: auto;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

.fa-solid::before,
.fa-brands::before {
  content: var(--fa);
}

.fa-solid {
  --fa-family: "${styles.solid.family}";
  --fa-style: ${styles.solid.weight};
}

.fa-brands {
  --fa-family: "${styles.brands.family}";
  --fa-style: ${styles.brands.weight};
}

${Object.entries(utilities)
  .filter(([name]) => used.has(name))
  .map(([, rule]) => rule)
  .join("\n")}

${rules.join("\n\n")}
`;

writeFileSync(cssTarget, css);
console.log(`Wrote ${cssTarget}`);
