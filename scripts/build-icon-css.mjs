import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// Font Awesome ships ~2,000 icons across 86 KB of CSS. This site uses a few
// dozen, so we scan the source for the icons that are actually referenced and
// emit just those, keeping the render-blocking stylesheet small.

const faRoot = "node_modules/@fortawesome/fontawesome-free";
const scanRoots = ["src/components", "src/data", "src/layouts", "src/pages"];
const target = "src/styles/icons.css";

// Utility classes we support. Anything else found in the source is a hard
// error, so a newly used Font Awesome feature can't silently render as nothing.
const utilities = {
  "fa-rotate-90": ".fa-rotate-90{transform:rotate(90deg)}",
};
const styleClasses = new Set(["fa-solid", "fa-brands"]);

function readCss(name) {
  return readFileSync(join(faRoot, "css", name), "utf8");
}

// Font Awesome 7 declares each icon as `.fa-name{--fa:"\f09b"}`.
function codepoints(css) {
  const map = new Map();
  for (const [, selectors, value] of css.matchAll(
    /([^{}]+)\{--fa:"(\\[0-9a-f]+)"\}/g,
  )) {
    for (const selector of selectors.split(",")) {
      const name = selector.trim().replace(/^\./, "");
      if (/^fa-[a-z0-9-]+$/.test(name)) map.set(name, value);
    }
  }
  return map;
}

function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const path = join(dir, entry);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const solid = codepoints(readCss("fontawesome.min.css"));
const brands = codepoints(readCss("brands.min.css"));

const used = new Set();
for (const root of scanRoots) {
  for (const path of walk(root)) {
    const source = readFileSync(path, "utf8");
    for (const [name] of source.matchAll(/\bfa-[a-z][a-z0-9-]*/g)) used.add(name);
  }
}

const usedSolid = [];
const usedBrands = [];
const unknown = [];
for (const name of [...used].sort()) {
  if (styleClasses.has(name) || utilities[name]) continue;
  if (brands.has(name)) usedBrands.push(name);
  else if (solid.has(name)) usedSolid.push(name);
  else unknown.push(name);
}

if (unknown.length) {
  console.error(
    `Unknown Font Awesome classes: ${unknown.join(", ")}\n` +
      `Add them to the utilities map in ${import.meta.filename} if they are ` +
      `not icon names.`,
  );
  process.exit(1);
}

const rules = (names, map) =>
  names.map((name) => `.${name}{--fa:"${map.get(name)}"}`).join("\n");

const css = `/* Generated by scripts/build-icon-css.mjs. Do not edit by hand. */
/* Font Awesome Free ${JSON.parse(readFileSync(join(faRoot, "package.json"), "utf8")).version} by @fontawesome - https://fontawesome.com
   License - https://fontawesome.com/license/free (Icons: CC BY 4.0, Fonts: SIL OFL 1.1) */

@font-face {
  font-family: "Font Awesome 7 Free";
  font-style: normal;
  font-weight: 900;
  font-display: block;
  src: url("@fortawesome/fontawesome-free/webfonts/fa-solid-900.woff2") format("woff2");
}

@font-face {
  font-family: "Font Awesome 7 Brands";
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url("@fortawesome/fontawesome-free/webfonts/fa-brands-400.woff2") format("woff2");
}

.fa-solid,
.fa-brands {
  display: var(--fa-display, inline-block);
  width: var(--fa-width, 1.25em);
  font-family: var(--fa-family);
  font-style: normal;
  font-synthesis: none;
  font-variant: normal;
  font-weight: var(--fa-style);
  line-height: 1;
  text-align: center;
  text-rendering: auto;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

.fa-solid::before,
.fa-brands::before {
  content: var(--fa);
}

.fa-solid {
  --fa-family: "Font Awesome 7 Free";
  --fa-style: 900;
}

.fa-brands {
  --fa-family: "Font Awesome 7 Brands";
  --fa-style: 400;
}

${Object.entries(utilities)
  .filter(([name]) => used.has(name))
  .map(([, rule]) => rule)
  .join("\n")}

/* solid */
${rules(usedSolid, solid)}

/* brands */
${rules(usedBrands, brands)}
`;

writeFileSync(target, css);
console.log(
  `Wrote ${usedSolid.length} solid and ${usedBrands.length} brand icons to ${target}`,
);
